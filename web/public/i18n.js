/** 整句翻译：先把长词替换掉，避免「ミディアムボブ」被拆成两段 */
const LONGEST_FIRST = Object.entries(CATEGORY).sort((a, b) => b[0].length - a[0].length);

/** 仍然残留假名时，把已知的助词/连接词干掉，让中文读起来通顺 */
const PARTICLES = [
  [/を頭の後ろへ/g, '放脑后'],
  [/の後ろへ/g, '到后方'],
  [/に手を添える/g, '手轻搭'],
  [/で/g, ''],
  [/を/g, ''],
  [/に/g, ''],
  [/の/g, ''],
  [/へ/g, ''],
  [/と/g, ''],
  [/・/g, '·'],
];

export function zh(text, kind = 'category') {
  if (!text) return '';
  const s = String(text).trim();
  if (kind === 'category' && CATEGORY[s]) return CATEGORY[s];
  if (!/[\u3040-\u30ff\u4e00-\u9faf]/.test(s)) return s; // 纯英文/编号原样返回
  let out = s;
  for (const [ja, cn] of LONGEST_FIRST) {
    if (ja.length < 2) continue; // 单字（春/夏/秋/冬…）只在分类精确匹配时替换，避免误伤
    out = out.split(ja).join(cn);
  }
  // 姿势名里的日文助词/词尾没有独立含义，清掉后中文更通顺
  if (kind === 'title' && /[\u3040-\u30ff]/.test(out)) {
    for (const [re, rep] of PARTICLES) out = out.replace(re, rep);
  }
  // 标题类文本：仍残留的假名（多为「て」「る」「し」等词尾）直接去掉，避免中英日混排
  if ((kind === 'title' || kind === 'text') && /[\u3040-\u30ff]/.test(out)) {
    out = out.replace(/[\u3040-\u30ff]+/g, '');
    out = out.replace(/·{2,}/g, '·').replace(/^·|·$/g, '').replace(/（）|\(\)/g, '').trim();
  }
  return out;
}

export const zhCats = (arr = []) => arr.map((c) => zh(c, 'category'));
export const zhTags = (arr = []) => arr.map((t) => zh(t, 'tag'));
